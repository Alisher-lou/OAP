# 3-тапсырма: жылдың кібісе жыл екенін анықтау
# Шарт: 400-ге бөлінсе немесе 4-ке бөлініп, 100-ге бөлінбесе

year_s = input("Жылды енгізіңіз: ").strip()

# Кіріс деректерін тексеру
if not year_s.isdigit():
    print("Қате енгізу: жыл бүтін оң сан болуы керек")
else:
    year = int(year_s)
    if year == 0:
        print("Қате енгізу: 0 жыл болмайды")
    elif year % 400 == 0 or (year % 4 == 0 and year % 100 != 0):   # құрама шарт
        print(year, "- кібісе жыл")
    else:
        print(year, "- кібісе жыл емес")