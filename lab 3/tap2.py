# 2-тапсырма: студенттің емтиханға жіберілуін анықтау
# Шарт: балл >= 50 және қатысу >= 70%

score_s = input("Балл (0-100): ").strip()
att_s = input("Қатысу (0-100%): ").strip()

# Кіріс деректерін тексеру
if not (score_s.isdigit() and att_s.isdigit()):
    print("Қате енгізу: бүтін оң сан енгізу керек")
else:
    score = int(score_s)
    attendance = int(att_s)
    if score > 100 or attendance > 100:          # аралықтан тыс мән
        print("Қате енгізу: мәндер 0 мен 100 аралығында болуы тиіс")
    elif score >= 50 and attendance >= 70:       # құрама шарт
        print("Емтиханға жіберіледі")
    else:
        if score < 50:                           # кірістірілген шарт: себебін көрсету
            print("Жіберілмейді: балл 50-ден төмен")
        else:
            print("Жіберілмейді: қатысу 70%-дан төмен")