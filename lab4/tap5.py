# 5-тапсырма. Түзетілген цикл
# Бастапқы кодтағы қате: i айнымалысы өзгермеді, сондықтан цикл шексіз болды

i = 1                                 # бастапқы мән беру
while i <= 10:                        # жалғасу шарты
    print(i)                          # цикл денесі
    i += 1                            # басқарушы айнымалыны өзгерту