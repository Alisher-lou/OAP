# 1-тапсырма. Шарты алдын тексерілетін цикл (while)
# Пайдаланушы оң бүтін сан енгізгенше енгізу қайталанады

text = input("Оң бүтін сан енгізіңіз: ").strip()

# Шарт цикл денесі орындалмас БҰРЫН тексеріледі
while not (text.isdigit() and int(text) > 0):
    print("Қате: сан бүтін және оң болуы тиіс.")
    text = input("Оң бүтін сан енгізіңіз: ").strip()

number = int(text)
print("Сіз енгізген сан:", number)